const idToEn = Object.fromEntries(
  Object.entries(enToId).map(([english, indonesia]) => [indonesia, english])
) as Record<string, string>;

export function translateText(value: string, language: Language) {
  const trimmed = value.trim();

  if (!trimmed) {
    return value;
  }

  const dictionary = language === "id" ? enToId : idToEn;
  const translated = dictionary[trimmed as keyof typeof dictionary];

  if (!translated) {
    const phraseEntry = Object.entries(dictionary)
      .filter(([source]) => source.length >= 8 && trimmed.includes(source))
      .sort((a, b) => b[0].length - a[0].length)[0];

    if (!phraseEntry) {
      return value;
    }

    return value.replace(phraseEntry[0], phraseEntry[1]);
  }

  return value.replace(trimmed, translated);
}
